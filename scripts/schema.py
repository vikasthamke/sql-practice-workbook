def engine_type(token, engine):
    """Return the concrete column type for an engine ('pg' or 'mysql')."""
    base = token.split("(")[0]
    if base in TYPE_MAP:
        pg, my = TYPE_MAP[base]
        return pg if engine == "pg" else my
    return token


