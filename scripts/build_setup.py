#!/usr/bin/env python3
"""
Build the two setup scripts from scripts/schema.py and data/*.csv:

  setup.sql         PostgreSQL 16+  (psql -d sql_workbook -f setup.sql)
  setup_mysql.sql   MySQL 8.0+      (mysql sql_workbook < setup_mysql.sql)

Both scripts create the same 32 tables and load the same rows, so every
portable query returns the same answer on both engines.
"""
import csv
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from schema import TABLES, index_ddl, table_ddl  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DATA = os.path.join(ROOT, "data")
BATCH = 500
NUMERIC = ("INT", "BIGINT", "SMALLINT", "DECIMAL", "DOUBLE")


def literal(raw, col):
    if raw == "":
        return "NULL"
    t = col["type"].split("(")[0]
    if t in NUMERIC or t.startswith("DOUBLE"):
        float(raw)  # validate
        return raw
    if t == "BOOLEAN":
        return {"true": "TRUE", "false": "FALSE"}[raw]
    if "\\" in raw:
        raise ValueError(f"backslash in {col['name']}: {raw!r} (not portable to MySQL)")
    return "'" + raw.replace("'", "''") + "'"


def load_rows(t):
    with open(os.path.join(DATA, f"{t['name']}.csv"), encoding="utf-8", newline="") as fh:
        r = csv.reader(fh)
        header = next(r)
        assert header == [c["name"] for c in t["columns"]], f"header mismatch in {t['name']}"
        return list(r)


HEADER = """-- =====================================================================
-- SQL Practice Workbook -- {engine} setup script
-- Fictional company: Lumen Analytics (SaaS data platform + AI features)
--
-- {run}
--
-- Generated by scripts/build_setup.py from scripts/schema.py and data/*.csv.
-- Do not edit by hand: change the generator and rebuild instead.
-- Re-running this script drops and recreates all workbook tables.
-- All timestamps are UTC without time zone. "Today" for the workbook is
-- 2025-07-01 (the data ends at 2025-06-30 23:59:59).
-- =====================================================================
"""


def build(engine):
    out = []
    if engine == "pg":
        out.append(HEADER.format(engine="PostgreSQL 16+",
                                 run="Run:  createdb sql_workbook && psql -d sql_workbook -f setup.sql"))
        out.append("SET client_encoding = 'UTF8';\nSET client_min_messages = warning;\n")
        for t in reversed(TABLES):
            out.append(f"DROP TABLE IF EXISTS {t['name']} CASCADE;")
        out.append("")
    else:
        out.append(HEADER.format(engine="MySQL 8.0+",
                                 run="Run:  mysql -e \"CREATE DATABASE sql_workbook CHARACTER SET utf8mb4\" && mysql sql_workbook < setup_mysql.sql"))
        out.append("SET NAMES utf8mb4;\nSET FOREIGN_KEY_CHECKS = 0;")
        for t in reversed(TABLES):
            out.append(f"DROP TABLE IF EXISTS {t['name']};")
        out.append("SET FOREIGN_KEY_CHECKS = 1;\n")

    out.append("-- ---------------------------------------------------------------- tables")
    for t in TABLES:
        out.append(f"-- {t['name']}: {t['grain']}")
        out.append(table_ddl(t, engine) + "\n")

    out.append("-- ------------------------------------------------------------------ data")
    out.append("BEGIN;" if engine == "pg" else "SET autocommit = 0;")
    for t in TABLES:
        data = load_rows(t)
        cols = ", ".join(c["name"] for c in t["columns"])
        out.append(f"-- {t['name']}: {len(data)} rows")
        for i in range(0, len(data), BATCH):
            chunk = data[i:i + BATCH]
            vals = ",\n".join("(" + ", ".join(literal(v, c) for v, c in zip(r, t["columns"])) + ")"
                              for r in chunk)
            out.append(f"INSERT INTO {t['name']} ({cols}) VALUES\n{vals};")
    out.append("COMMIT;")
    if engine == "mysql":
        out.append("SET autocommit = 1;")

    out.append("\n-- --------------------------------------------------------------- indexes")
    for t in TABLES:
        for stmt in index_ddl(t):
            out.append(stmt)

    out.append("\n-- ------------------------------------------------------------ statistics")
    if engine == "pg":
        out.append("ANALYZE;")
    else:
        out.append("ANALYZE TABLE " + ", ".join(t["name"] for t in TABLES) + ";")

    out.append("\n-- ---------------------------------------------- verification: row counts")
    parts = [f"SELECT '{t['name']}' AS table_name, COUNT(*) AS row_count FROM {t['name']}" for t in TABLES]
    out.append("\nUNION ALL ".join(parts) + "\nORDER BY table_name;")
    return "\n".join(out) + "\n"


def build_csv_loader(engine):
    """DDL + bulk load from data/*.csv (psql \\copy / MySQL LOAD DATA LOCAL INFILE)."""
    full = build(engine)
    ddl = full.split("-- ------------------------------------------------------------------ data")[0]
    tail = full.split("-- --------------------------------------------------------------- indexes")[1]
    out = [ddl.replace("setup script", "CSV loader").replace("Run:  createdb sql_workbook && psql -d sql_workbook -f setup.sql",
                                                             "Run from the project folder:  psql -d sql_workbook -f load_csv_postgresql.sql")
              .replace("mysql sql_workbook < setup_mysql.sql",
                       "mysql --local-infile=1 sql_workbook < load_csv_mysql.sql   (server: local_infile=ON)")]
    out.append("-- ------------------------------------------------------------- csv load")
    for t in TABLES:
        cols = [c["name"] for c in t["columns"]]
        if engine == "pg":
            out.append(f"\\copy {t['name']} ({', '.join(cols)}) FROM 'data/{t['name']}.csv' WITH (FORMAT csv, HEADER true)")
        else:
            vars_ = ", ".join(f"@{c}" for c in cols)
            sets = []
            for c in t["columns"]:
                ty = c["type"].split("(")[0]
                if ty == "BOOLEAN":
                    sets.append(f"{c['name']} = CASE @{c['name']} WHEN 'true' THEN 1 WHEN 'false' THEN 0 END")
                else:
                    sets.append(f"{c['name']} = NULLIF(@{c['name']}, '')")
            out.append(f"LOAD DATA LOCAL INFILE 'data/{t['name']}.csv' INTO TABLE {t['name']}\n"
                       f"  CHARACTER SET utf8mb4 FIELDS TERMINATED BY ',' OPTIONALLY ENCLOSED BY '\"' ESCAPED BY ''\n"
                       f"  LINES TERMINATED BY '\\n' IGNORE 1 LINES\n  ({vars_})\n  SET {', '.join(sets)};")
    out.append("\n-- --------------------------------------------------------------- indexes" + tail)
    return "\n".join(out)


def main():
    for engine, name in (("pg", "load_csv_postgresql.sql"), ("mysql", "load_csv_mysql.sql")):
        path = os.path.join(ROOT, name)
        with open(path, "w", encoding="utf-8") as fh:
            fh.write(build_csv_loader(engine))
        print(f"wrote {name}")
    for engine, name in (("pg", "setup.sql"), ("mysql", "setup_mysql.sql")):
        path = os.path.join(ROOT, name)
        with open(path, "w", encoding="utf-8") as fh:
            fh.write(build(engine))
        print(f"wrote {name} ({os.path.getsize(path) / 1e6:.1f} MB)")


if __name__ == "__main__":
    main()
